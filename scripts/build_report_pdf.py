def embed_image(path, max_width=None, max_height=280):
    if max_width is None:
        max_width = AVAIL
    pil = PILImage.open(path)
    ow, oh = pil.size
    ratio = min(max_width / ow, max_height / oh, 1.0)
    return Image(path, width=ow * ratio, height=oh * ratio)


def make_table(headers, rows, ratios, align_first_left=True):
    data = [[Paragraph('<b>%s</b>' % h, S['th']) for h in headers]]
    for r in rows:
        row = []
        for ci, cell in enumerate(r):
            st = S['tdl'] if (ci == 0 and align_first_left) else S['td']
            row.append(Paragraph(str(cell), st))
        data.append(row)
    widths = [x * AVAIL for x in ratios]
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(('BACKGROUND', (0, i), (-1, i), TABLE_ROW_ODD if i % 2 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    return t


